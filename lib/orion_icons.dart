class OIcon extends StatelessWidget {
  final Path Function() pathBuilder;
  final double size;
  final Color color;
  const OIcon(this.pathBuilder, {super.key, this.size = 20, required this.color});

  @override
  Widget build(BuildContext context) => CustomPaint(
    size: Size(size, size),
    painter: _OIconPainter(pathBuilder(), color, size),
  );
}

class _OIconPainter extends CustomPainter {
  final Path path;
  final Color color;
  final double size;
  _OIconPainter(this.path, this.color, this.size);
  @override
  void paint(Canvas canvas, Size s) {
    final scale = size / 24.0;
    canvas.scale(scale);
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.8
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;
    canvas.drawPath(path, paint);
  }
  @override
  bool shouldRepaint(_OIconPainter old) => old.color != color || old.size != size;
}
